#!/usr/bin/env python3
"""blog-redirect-worker.py -- write dist/_worker.js: every <prefix>.blog.tcos.us
request 301s to that person's media host, old post URLs included.

One host per person (operator, 2026-09-05/06): <prefix>.media.tcos.us. The
blog hosts stay as redirects. Cloudflare Pages' _redirects file is
path-only, it cannot see the hostname, so the mapping is a tiny Pages
worker: hostnames that map get redirected, everything else is served from
the static assets exactly as before.

Post URLs: /profiles/<oper>/blog/[NNN-]<slug>.(md|html) -> /posts/<slug>.html
(the numbered prefix was dropped 2026-09-05; stripping ^\\d{3}- covers every
old name without a list -- exactly three digits, date-named slugs keep their year). A top-level page (/<name> or /<name>.html) -> /posts/<name>.html: the hand-built standalone pages are posts now. Anything else on a blog host -> the media root.

Input: dist/people.json (subdomain_prefix, media_dns). A person with no
media_dns keeps a working blog host -- no redirect is emitted for them.

Usage: blog-redirect-worker.py dist/people.json dist/_worker.js
"""
import json
import sys

WORKER = """// generated by bin/blog-redirect-worker.py -- do not edit
const MEDIA = %(map)s;
export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    const m = url.hostname.match(/^([a-z0-9-]+)\\.blog\\.tcos\\.us$/);
    if (m && MEDIA[m[1]]) {
      const target = "https://" + MEDIA[m[1]];
      const p = url.pathname.match(/^\\/profiles\\/[^/]+\\/blog\\/(?:\\d{3}-)?([^/]+?)(?:\\.md|\\.html)?$/);
      if (p) return Response.redirect(target + "/posts/" + p[1] + ".html", 301);
      // the resume used to live here as /resume-<slug>.html and /profiles/<slug>/dist/resume.<ext>
      const r = url.pathname.match(/^\\/(?:resume-[^/]+|profiles\\/[^/]+\\/dist\\/resume)\\.(html|pdf|md|txt)$/);
      if (r) return Response.redirect(target + "/resume." + r[1], 301);
      // A top-level page (/lg-webos, /lg-webos.html) is a post now: the two
      // hand-built standalone pages became profiles/<oper>/blog/*.md on
      // 2026-09-10. Lost 2026-09-05..10 behind the catch-all below. /index is the root.
      const s = url.pathname.match(/^\\/([^/.]+)(?:\\.html)?$/);
      if (s && s[1] !== "index") return Response.redirect(target + "/posts/" + s[1] + ".html", 301);
      return Response.redirect(target + "/", 301);
    }
    // The hub hosts: media.tcos.us and blog.tcos.us are the index of every
    // operator, nothing else. "/" serves the hub page under its clean name
    // (asking for /media-hub.html made the assets layer answer 308 to
    // /media-hub -- the first prod deploy did that). Any other path that
    // is not the hub's own data or static assets goes back to "/": the
    // resume app's catch-all used to answer 200 "Loading..." for
    // media.tcos.us/people (2026-09-06).
    if (url.hostname === "media.tcos.us" || url.hostname === "blog.tcos.us") {
      const hub = url.hostname === "media.tcos.us" ? "/media-hub" : "/blog-hub";
      const path = url.pathname;
      if (path === "/" || path === "/index.html" || path === hub || path === hub + ".html") {
        return env.ASSETS.fetch(new Request(new URL(hub, url).toString(), request));
      }
      const keep = ["/people.json", "/manifest.json", "/favicon.ico", "/assets/", "/badges/", "/icons/"];
      if (!keep.some((k) => path.startsWith(k))) return Response.redirect(url.origin + "/", 301);
    }
    return env.ASSETS.fetch(request);
  },
};
"""


def main(people_path, out_path):
    people = json.load(open(people_path))
    mapping = {p["subdomain_prefix"]: p["media_dns"] for p in people if p.get("media_dns")}
    open(out_path, "w").write(WORKER % {"map": json.dumps(mapping, indent=2)})
    print(f"[+] {out_path}: {len(mapping)} blog host(s) redirect to media: {', '.join(sorted(mapping))}")
    return 0


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    sys.exit(main(sys.argv[1], sys.argv[2]))
