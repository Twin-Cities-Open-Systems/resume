# bin/oh_shit_git-node_modules_commit.bash

# 1. Purge the accidental tracking entries from your git staging area
git reset

# 2. Build the strict, persistent workspace ignore file
cat << 'EOF' > .gitignore
node_modules/
package-lock.json
.wrangler/
dist/
EOF

# 3. Pull and execute the official NVM manager using the complete canonical URL
curl -o- https://githubusercontent.com | bash

# 4. Source the fresh shell context layers to register the nvm binary
export NVM_DIR="$HOME/.nvm"
[ -s "$NVM_DIR/nvm.sh" ] && \. "$NVM_DIR/nvm.sh"

# 5. Install and lock down the stable Node.js v22 runtime environment
nvm install 22
nvm use 22

# 6. Securely stage only the authorized structural source tree tracks
git add .gitignore package.json bin/ profiles/ tests/ convert.sh

# 7. Push the compiled profile matrix straight to the Cloudflare Edge routes
npx wrangler worker deploy --var PEOPLE_MANIFEST="$(cat dist/people.json)"

